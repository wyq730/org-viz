const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    const requests = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('request', (request) => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
    await page.goto(pathToFileURL(path.resolve('index.html')).href);
    assert.equal(await page.locator('#expand-all').isDisabled(), true);
    assert.equal(await page.locator('#collapse-all').isDisabled(), true);
    await page.click('#demo');
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node').count(), 18);
    const rootCounter = page.locator('[data-toggle="demo-0"] text');
    assert.match(await rootCounter.textContent(), /直属 3 · 全部 28/);
    assert.match(await page.locator('[data-toggle="demo-29"] text').textContent(), /直属 4 · 全部 4/);
    await page.screenshot({ path: '/tmp/org-viz-demo.png' });
    const originalScale = await page.locator('#reset-zoom').textContent();
    await page.click('#zoom-out');
    assert.notEqual(await page.locator('#reset-zoom').textContent(), originalScale);
    await page.click('#reset-zoom');
    assert.equal(await page.locator('#reset-zoom').textContent(), '100%');
    await page.click('#fit');
    await page.waitForTimeout(350);
    const toggle = page.locator('[data-toggle="demo-1"]');
    const before = await toggle.boundingBox();
    await toggle.click();
    const after = await page.locator('[data-toggle="demo-1"]').boundingBox();
    assert.ok(Math.abs(after.x - before.x) < 1 && Math.abs(after.y - before.y) < 1, 'Toggle anchor remains stationary');
    assert.match(await rootCounter.textContent(), /直属 3 · 全部 28/, 'Counts include collapsed descendants');
    await page.click('#expand-all');
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node').count(), 34);
    await page.click('#collapse-all');
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node').count(), 2);
    assert.match(await rootCounter.textContent(), /直属 3 · 全部 28/);
    await page.fill('#search', '团队伙伴 17');
    assert.equal(await page.locator('.result').count(), 1);
    await page.press('#search', 'ArrowDown');
    await page.press('#search', 'Enter');
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node.selected').getAttribute('data-node'), 'demo-24');
    await page.locator('.node.selected').click();
    assert.equal(await page.locator('#details').isVisible(), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#details').isVisible(), false);
    await page.fill('#search', 'not-found');
    assert.match(await page.locator('#results').textContent(), /没有找到/);
    await page.fill('#search', '');
    const countBefore = await page.locator('.node').count();
    const upload = async (records) => page.setInputFiles('#file', { name: 'test.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(records)) });
    await upload([{ node: 'a', name: 'A', parent: 'b' }, { node: 'b', name: 'B', parent: 'a' }]);
    await page.waitForTimeout(50);
    assert.match(await page.locator('#notice').textContent(), /循环/);
    assert.equal(await page.locator('.node').count(), countBefore);
    await upload([{ node: 'one', name: '<img src=x onerror=alert(1)>', parent: 'missing', abstract: ['中文长部门路径'.repeat(6), '第二行', '第三行', '第四行'], other_info: { note: '<script>alert(1)</script>' } }]);
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node').count(), 1);
    assert.equal(await page.locator('.node-abstract').count(), 4);
    assert.equal(await page.locator('img').count(), 0);
    assert.match(await page.locator('#summary').textContent(), /缺失父节点/);
    const fullPath = path.resolve('dr_org_data/org_export_20261120/org_export_nodes_2026-11-20.json');
    if (fs.existsSync(fullPath)) {
      await page.setInputFiles('#file', fullPath);
      await page.waitForTimeout(400);
      assert.match(await page.locator('#summary').textContent(), /1,335 个节点 · 2 棵树/);
      const records = JSON.parse(fs.readFileSync(fullPath, 'utf8'));
      const record = records[records.length - 5];
      await page.fill('#search', record.name);
      await page.press('#search', 'Enter');
      await page.waitForTimeout(350);
      assert.equal(await page.locator('.node.selected').count(), 1);
      await page.click('#expand-all');
      await page.waitForTimeout(400);
      assert.equal(await page.locator('.node').count(), 1335);
      const visibleScale = await page.locator('#reset-zoom').textContent();
      assert.notEqual(visibleScale, '100%');
      console.log(`Full dataset: 1335 nodes rendered, fit scale ${visibleScale}`);
      await page.click('#collapse-all');
      await page.waitForTimeout(350);
      assert.equal(await page.locator('.node').count(), 2);
      await page.evaluate(() => document.getElementById('demo').click());
      await page.waitForTimeout(350);
    }
    await page.mouse.move(800, 600);
    const transformBefore = await page.locator('#scene').getAttribute('transform');
    await page.mouse.wheel(0, 200);
    await page.waitForTimeout(50);
    assert.notEqual(await page.locator('#scene').getAttribute('transform'), transformBefore);
    await page.mouse.move(1200, 700);
    await page.mouse.down();
    await page.mouse.move(1100, 650, { steps: 5 });
    await page.mouse.up();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.click('#fit');
    await page.waitForTimeout(350);
    await page.screenshot({ path: '/tmp/org-viz-mobile.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const toolbar = await page.locator('.controls').boundingBox();
    assert.ok(toolbar.x >= 0 && toolbar.x + toolbar.width <= 390, 'Toolbar fits narrow viewport');
    const dropData = await page.evaluateHandle(() => {
      const transfer = new DataTransfer();
      transfer.items.add(new File([JSON.stringify([
        {node:'drop-1', name:'Same Name', parent:'', other_info:{note:'hello'}},
        {node:'drop-2', name:'Same Name', parent:'drop-1'}
      ])], 'drop.json', {type:'application/json'}));
      return transfer;
    });
    await page.dispatchEvent('#workspace', 'dragenter', {dataTransfer:dropData});
    assert.equal(await page.locator('#drop-overlay').isVisible(), true);
    await page.dispatchEvent('#workspace', 'drop', {dataTransfer:dropData});
    await page.waitForTimeout(50);
    assert.equal(await page.locator('#drop-overlay').isVisible(), false);
    assert.equal(await page.locator('.node').count(), 2);
    assert.equal(await page.locator('#notice').isVisible(), false);
    await page.fill('#search', 'same name');
    assert.equal(await page.locator('.result').count(), 2);
    await page.press('#search', 'ArrowDown');
    await page.press('#search', 'ArrowDown');
    await page.press('#search', 'Enter');
    await page.waitForTimeout(350);
    assert.equal(await page.locator('.node.selected').getAttribute('data-node'), 'drop-2');
    await page.locator('.node.selected').click();
    const popup = await page.locator('#details').boundingBox();
    assert.ok(popup.x >= 0 && popup.x + popup.width <= 390 && popup.y >= 76 && popup.y + popup.height <= 844);
    await upload([{node:'a', name:'A', parent:''}, {node:'a', name:'B', parent:''}]);
    await page.waitForTimeout(50);
    assert.match(await page.locator('#notice').textContent(), /重复/);
    assert.equal(await page.locator('.node').count(), 2);
    await upload([{node:'a', name:'A', parent:'', abstract:'wrong'}]);
    await page.waitForTimeout(50);
    assert.match(await page.locator('#notice').textContent(), /abstract/);
    assert.equal(await page.locator('.node').count(), 2);
    assert.deepEqual(errors, []);
    assert.deepEqual(requests, []);
    console.log('PASS: file:// loading, demo, zoom, anchor stability, hidden-node search, keyboard, popup, validation, text safety, full dataset, pan, mobile, no network or runtime errors');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
